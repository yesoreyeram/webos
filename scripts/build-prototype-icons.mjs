export function extractInner(svg) {
  const match = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!match) throw new Error('Not an SVG document');
  return match[1].replace(/\s*\n\s*/g, '').trim();
}

function build() {
  const icons = {};
  for (const name of ICON_NAMES) {
    icons[name] = extractInner(readFileSync(join(iconsDir, `${name}.svg`), 'utf8'));
  }
  const banner =
    '// Generated by scripts/build-prototype-icons.mjs. Do not edit.\n' +
    '// Icons: Lucide (https://lucide.dev), ISC License.\n';
  writeFileSync(out, `${banner}window.ICONS = ${JSON.stringify(icons, null, 0)};\n`);
  console.log(`Wrote ${Object.keys(icons).length} icons to ${out}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build();
